"""Turns the TTF fonts in fonts/ into smooth (anti-aliased) VLW fonts for M5GFX/LovyanGFX and writes
them as C arrays to lib/ui/src/fonts/. Run it after changing a size or a character set:

    pip install pillow fonttools
    python tools/make_fonts.py

VLW layout (as read by lgfx::VLWfont): a header of six big-endian int32s (glyph count, version 11,
font size, 0, ascent, descent), then seven int32s per glyph (code point, height, width, advance,
top above the baseline, left offset, 0), then each glyph's 8-bit alpha bitmap in the same order.
"""
import os
import struct

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'lib', 'ui', 'src', 'fonts')

ASCII = ''.join(chr(c) for c in range(32, 127))
EXTRA = '°µ³₂·’–…'
DIGITS = ' 0123456789,.-–°%'

# name, file, pixel size, letter spacing in px, characters
FONTS = [
    ('serif_hero', 'Fraunces-600.ttf', 104, -2, DIGITS),          # the big number
    ('serif_head', 'Fraunces-600.ttf', 44, -0.4, ASCII + EXTRA),  # the headline
    ('serif_value', 'Fraunces-600.ttf', 27, 0, DIGITS),           # values in the bottom row
    ('sans_body', 'Manrope-600.ttf', 20, 0, ASCII + EXTRA),       # sentences under the headline
    ('sans_strong', 'Manrope-700.ttf', 19, 0, ASCII + EXTRA),     # the unit under the big number
    ('sans_note', 'Manrope-600.ttf', 16, 0, ASCII + EXTRA),       # the note under the unit
    ('sans_small', 'Manrope-600.ttf', 14, 0, ASCII + EXTRA),      # chart labels, units
    ('sans_caps', 'Manrope-700.ttf', 13, 1.5, ASCII + EXTRA),     # small uppercase labels
]


def glyph(font, ch, tracking=0):
    """(bitmap, width, height, advance, top, left) for one character."""
    x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
    advance = round(font.getlength(ch) + tracking)
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    if w == 0 or h == 0:
        return b'', 0, 0, advance, 0, 0
    img = Image.new('L', (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, anchor='ls', fill=255)
    return img.tobytes(), w, h, advance, -y0, x0


def subscript_two(path, size, tracking):
    """A ₂ made from a smaller 2, for fonts that don't have one."""
    small = ImageFont.truetype(path, round(size * 0.62))
    bmp, w, h, adv, top, left = glyph(small, '2', tracking)
    return bmp, w, h, adv, top - round(size * 0.16), left


def vlw(path, size, tracking, chars):
    font = ImageFont.truetype(path, size)
    cmap = TTFont(path).getBestCmap()
    ascent, descent = font.getmetrics()
    glyphs = []
    for ch in sorted(set(chars)):
        if ord(ch) in cmap:
            glyphs.append((ord(ch),) + glyph(font, ch, tracking))
        elif ch == '₂':
            glyphs.append((ord(ch),) + subscript_two(path, size, tracking))
    out = struct.pack('>6i', len(glyphs), 11, size, 0, ascent, descent)
    for code, bmp, w, h, adv, top, left in glyphs:
        out += struct.pack('>7i', code, h, w, adv, top, left, 0)
    for g in glyphs:
        out += g[1]
    return out, len(glyphs)


def main():
    os.makedirs(OUT, exist_ok=True)
    names = []
    for name, file, size, tracking, chars in FONTS:
        data, n = vlw(os.path.join(ROOT, 'fonts', file), size, tracking, chars)
        lines = [', '.join(f'0x{b:02x}' for b in data[i:i + 24]) for i in range(0, len(data), 24)]
        with open(os.path.join(OUT, f'{name}.h'), 'w') as f:
            licence = 'OFL-fraunces.txt' if file.startswith('Fraunces') else 'OFL-manrope.txt'
            f.write(f'// Generated by tools/make_fonts.py from fonts/{file} at {size} px ({n} glyphs). Do not edit.\n')
            f.write(f'// Font Software under the SIL Open Font License 1.1: see fonts/{licence}\n')
            f.write('#pragma once\n#include <cstdint>\n\n')
            f.write(f'static const uint8_t {name}[] = {{\n  ' + ',\n  '.join(lines) + '\n};\n')
        names.append(name)
        print(f'{name}: {n} glyphs, {len(data) / 1024:.0f} KB')
    with open(os.path.join(OUT, 'fonts.h'), 'w') as f:
        f.write('// Generated by tools/make_fonts.py. Do not edit.\n#pragma once\n')
        f.write(''.join(f'#include "{n}.h"\n' for n in names))


if __name__ == '__main__':
    main()
